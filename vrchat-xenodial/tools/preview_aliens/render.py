"""Draw a contact sheet of every alien from the real generator's output.

  bash tools/preview_aliens/preview.sh     (compiles the generator with Mono, then runs this)

Shading matches the in-world XenoDial/ToonVertexColor shader.
"""
import json, math, sys
import numpy as np
from PIL import Image, ImageDraw, ImageFont

SUN = np.array([0.45, 0.8, 0.35]); SUN /= np.linalg.norm(SUN)
CELL_W, CELL_H, SS = 230, 270, 2          # cell size, supersampling
COLS = 10


def font(size, bold=False):
    for f in (["DejaVuSans-Bold.ttf"] if bold else []) + ["DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"]:
        try:
            return ImageFont.truetype(f, size)
        except OSError:
            pass
    return ImageFont.load_default()


def rot(yaw, pitch):
    cy, sy, cp, sp = math.cos(yaw), math.sin(yaw), math.cos(pitch), math.sin(pitch)
    ry = np.array([[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]])
    rx = np.array([[1, 0, 0], [0, cp, -sp], [0, sp, cp]])
    return rx @ ry


def draw_alien(alien, w, h, yaw=math.radians(-28), pitch=math.radians(-10)):
    img = Image.new("RGB", (w * SS, h * SS), (34, 40, 48))
    d = ImageDraw.Draw(img)
    verts, tris = [], []
    for p in alien["pieces"]:
        v = np.array(p["v"], dtype=np.float32).reshape(-1, 10)
        t = np.array(p["t"], dtype=np.int64).reshape(-1, 3) + sum(len(x) for x in verts)
        verts.append(v); tris.append(t)
    v = np.concatenate(verts); t = np.concatenate(tris)
    pos, nrm, col, glow = v[:, :3], v[:, 3:6], v[:, 6:9], v[:, 9]
    light = 0.38 + 0.52 * np.clip(nrm @ SUN, 0, 1) + 0.18 * (0.5 + 0.5 * nrm[:, 1])
    shade = col * (light + (1 - light) * np.clip(glow, 0, 1))[:, None]
    R = rot(yaw, pitch)
    cam = pos @ R.T                                  # x right?, y up, z toward the viewer after flip below
    sx, sy, depth = -cam[:, 0], cam[:, 1], cam[:, 2]
    # fit the model (all aliens share one scale so they compare)
    scale = (h * SS) * 0.80 / 2.6
    cx, cy = w * SS / 2, h * SS * 0.92
    px = cx + sx * scale
    py = cy - sy * scale
    # cull faces pointing away (normal toward -viewer), then paint far to near
    facen = nrm[t].mean(axis=1) @ R.T
    keep = facen[:, 2] > -0.05
    t = t[keep]
    order = np.argsort(depth[t].mean(axis=1))
    for tri in t[order]:
        c = np.clip(shade[tri].mean(axis=0), 0, 1)
        d.polygon([(px[i], py[i]) for i in tri], fill=tuple(int(255 * x) for x in c))
    # ground shadow line
    return img.resize((w, h), Image.LANCZOS)


def main(src, out, start=0, count=None):
    aliens = json.load(open(src))
    aliens = aliens[start:start + count if count else None]
    rows = math.ceil(len(aliens) / COLS)
    sheet = Image.new("RGB", (COLS * CELL_W, rows * CELL_H + 70), (20, 24, 30))
    d = ImageDraw.Draw(sheet)
    d.text((16, 18), f"XenoDial aliens {start + 1}-{start + len(aliens)} (generated by Assets/XenoDial/Editor/XenoDialAliens.cs)",
           fill=(46, 255, 204), font=font(26, True))
    f1, f2 = font(17, True), font(12)
    for i, a in enumerate(aliens):
        r, c = divmod(i, COLS)
        x0, y0 = c * CELL_W, 70 + r * CELL_H
        sheet.paste(draw_alien(a, CELL_W - 8, CELL_H - 58), (x0 + 4, y0 + 4))
        d.text((x0 + 8, y0 + CELL_H - 52), f"#{start + i + 1} {a['name']}", fill=(240, 240, 240), font=f1)
        desc = a["desc"]
        if len(desc) > 36:
            cut = desc.rfind(" ", 0, 36)
            desc = desc[:cut] + "\n" + desc[cut + 1:]
        d.text((x0 + 8, y0 + CELL_H - 30), desc, fill=(170, 200, 210), font=f2)
    sheet.save(out)
    print("wrote", out, sheet.size)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], *(int(x) for x in sys.argv[3:]))
